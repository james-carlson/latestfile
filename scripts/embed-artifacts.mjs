// Generates lib/embedded-artifacts.ts from the spec's companion files.
//
// These are read over HTTP at their canonical URLs (the schema's own $id, the
// examples the README points at). Reading them from disk at request time is
// fragile on Vercel: the serverless bundle only contains files Next's tracer
// can follow, and a path built from a lookup table is not traceable. Embedding
// the contents at build time removes the filesystem from the request path
// altogether.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();

const ARTIFACTS = [
  ["schemas/latestfile-v0.1.schema.json", "application/schema+json; charset=utf-8"],
  ["examples/personal/.latestfile", "text/plain; charset=utf-8"],
  ["examples/personal/.latestfile.json", "application/json; charset=utf-8"],
  ["examples/team/latestfile", "text/plain; charset=utf-8"],
  ["examples/team/latestfile.json", "application/json; charset=utf-8"],
  ["examples/org/latestfile", "text/plain; charset=utf-8"],
  ["examples/org/latestfile.json", "application/json; charset=utf-8"],
  ["examples/project/.latestfile", "text/plain; charset=utf-8"],
  ["examples/project/.latestfile.json", "application/json; charset=utf-8"],
];

const entries = [];
for (const [file, contentType] of ARTIFACTS) {
  const body = await readFile(path.join(root, file), "utf8");
  entries.push(
    `  ${JSON.stringify(file)}: {\n` +
      `    contentType: ${JSON.stringify(contentType)},\n` +
      `    body: ${JSON.stringify(body)},\n` +
      `  },`
  );
}

const out = `// GENERATED by scripts/embed-artifacts.mjs — do not edit.
// Regenerate with: node scripts/embed-artifacts.mjs

export interface EmbeddedArtifact {
  contentType: string;
  body: string;
}

/** Keyed by repository-relative path. */
export const EMBEDDED_ARTIFACTS: Record<string, EmbeddedArtifact> = {
${entries.join("\n")}
};
`;

await mkdir(path.join(root, "lib"), { recursive: true });
await writeFile(path.join(root, "lib/embedded-artifacts.ts"), out);
console.log(`embedded ${ARTIFACTS.length} artifacts`);
